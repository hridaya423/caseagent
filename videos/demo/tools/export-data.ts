// Exports the real case events the motion scenes draw, so no card on screen is typed by hand.
// Run from the repo root: node --import tsx videos/demo/tools/export-data.ts
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { isAgency, loadCase, type CaseEvent } from "../../../src/case/parse.ts";

const repo = fileURLToPath(new URL("../../../", import.meta.url));
const out = fileURLToPath(new URL("../content/cases.js", import.meta.url));

const flat = (t: string) => t.replace(/\*\*/g, "").replace(/\s+/g, " ").trim();
const headline = (t: string) => {
  // The agency's emails open with the property address; the card already names the property.
  const s = flat(t).replace(/^Address: .*?\b[A-Z]{1,2}\d\w? \d[A-Z]{2}\s*/, "");
  return s.length > 96 ? `${s.slice(0, 93).trimEnd()}…` : s;
};
const view = (e: CaseEvent) => ({
  n: e.n,
  at: e.at.replace(/:\d\d UTC$/, " UTC"),
  channel: e.channel,
  from: e.from,
  to: e.to,
  agency: isAgency(e.from),
  headline: headline(e.body),
});

const twin = loadCase(`${repo}evals/reality-sim/cases/110`);
const changed = loadCase(`${repo}evals/reality-sim/cases/206`);
const parent = loadCase(`${repo}data/public/Property Management/026`);

const before = flat(twin.events.at(-1)!.body);
const after = flat(changed.events.at(-1)!.body);
if (!after.startsWith(before)) throw new Error("206's last event no longer extends 110's");

const data = {
  title: changed.title,
  property: /Property:\*\*\s*(.+)/.exec(changed.details)?.[1].trim() ?? "",
  events: twin.events.map(view),
  last: { ...view(changed.events.at(-1)!), shared: before, added: after.slice(before.length).trim() },
  future: parent.events.filter((e) => e.n > twin.events.length).map(view),
};
writeFileSync(out, `// Generated by tools/export-data.ts from evals/reality-sim/cases/110, 206 and public case 026.\nwindow.CASE_DATA = ${JSON.stringify(data, null, 2)};\n`);
console.log(`${data.events.length} events, ${data.future.length} future events -> ${out}`);
